async function saveTeacherMarks(students, subjectId) {
  const markRows = [];
  const commentRows = [];
  students.forEach(stu => {
    const markVal = document.getElementById('tm-mark-' + stu.id).value;
    const commentVal = document.getElementById('tm-comment-' + stu.id).value.trim();
    if (markVal !== '') markRows.push({ student_id: stu.id, subject_id: subjectId, mark: Number(markVal) });
    if (commentVal !== '') commentRows.push({ student_id: stu.id, teacher_id: currentProfile.id, comment: commentVal });
  });

  if (markRows.length) {
    const { error } = await db.from('marks').upsert(markRows, { onConflict: 'student_id,subject_id' });
    if (error) { showStatus(error.message, true); return; }
  }
  for (const row of commentRows) {
    const { data: existing } = await db.from('teacher_comments')
      .select('id').eq('student_id', row.student_id).eq('teacher_id', row.teacher_id).maybeSingle();
    if (existing) {
      await db.from('teacher_comments').update({ comment: row.comment }).eq('id', existing.id);
    } else {
      await db.from('teacher_comments').insert(row);
    }
  }
  showStatus('Marks and comments saved.');
}

