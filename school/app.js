/* =========================================================================
   SCHOOL RESULT PORTAL
   Plain JS + Supabase. No build step. Open index.html in a browser.

   Expected Supabase schema (run this in the Supabase SQL editor):

   -- profiles table links to Supabase Auth users and stores role/name
   create table profiles (
     id uuid primary key references auth.users(id) on delete cascade,
     name text not null,
     role text not null check (role in ('admin','teacher'))
   );

   create table grades (
     id serial primary key,
     name text not null
   );

   create table subjects (
     id serial primary key,
     name text not null
   );

   create table students (
     id serial primary key,
     student_code text not null,
     name text not null,
     grade_id int references grades(id)
   );

   create table grade_subjects (
     grade_id int references grades(id),
     subject_id int references subjects(id),
     primary key (grade_id, subject_id)
   );

   create table teacher_subjects (
     teacher_id uuid references profiles(id),
     subject_id int references subjects(id),
     primary key (teacher_id, subject_id)
   );

   create table marks (
     id serial primary key,
     student_id int references students(id),
     subject_id int references subjects(id),
     mark numeric,
     unique (student_id, subject_id)
   );

   create table teacher_comments (
     id serial primary key,
     student_id int references students(id),
     teacher_id uuid references profiles(id),
     comment text
   );

   create table school_settings (
     key text primary key,
     value text
   );

   -- Suggested school_settings rows:
   -- ('school_name', 'ABC School')
   -- ('logo_url', 'https://.../logo.png')
   -- ('principal_name', 'Principal Name')
   -- ('report_footer', 'Generated by School Result Portal')

   Row Level Security: enable RLS on all tables and add policies so that
   admins (profiles.role = 'admin') can do anything, and teachers can only
   read/write marks & comments for subjects listed in teacher_subjects for
   their own id. This file assumes such policies exist server-side; it does
   not attempt to enforce permissions on its own beyond hiding UI.
   ========================================================================= */

