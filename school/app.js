async function doLogin() {
  const email = document.getElementById('login-email').value.trim();
  const password = document.getElementById('login-password').value;
  const errEl = document.getElementById('login-error');
  errEl.classList.add('hidden');

  if (!email || !password) {
    errEl.textContent = 'Enter your email and password.';
    errEl.classList.remove('hidden');
    return;
  }

  const { data, error } = await db.auth.signInWithPassword({ email, password });
  if (error) {
    errEl.textContent = error.message;
    errEl.classList.remove('hidden');
    return;
  }
  currentUser = data.user;
  await loadProfileAndEnter();
}

async function doLogout() {
  await db.auth.signOut();
  currentUser = null;
  currentProfile = null;
  showLogin();
}

async function loadProfileAndEnter() {
  const { data, error } = await db
    .from('profiles')
    .select('id,name,role')
    .eq('id', currentUser.id)
    .single();

  if (error || !data) {
    document.getElementById('login-error').textContent =
      'Logged in, but no profile found for this account. Ask the admin to add you.';
    document.getElementById('login-error').classList.remove('hidden');
    document.getElementById('login-wrap').classList.remove('hidden');
    document.getElementById('app-wrap').classList.add('hidden');
    return;
  }

  currentProfile = data;
  enterApp();
}

function enterApp() {
  document.getElementById('config-screen').classList.add('hidden');
  document.getElementById('login-wrap').classList.add('hidden');
  document.getElementById('app-wrap').classList.remove('hidden');
  document.getElementById('header-user-name').textContent =
    currentProfile.name + ' (' + currentProfile.role + ')';

  if (currentProfile.role === 'admin') {
    document.getElementById('admin-panel').classList.remove('hidden');
    document.getElementById('teacher-panel').classList.add('hidden');
    renderAdminPanel();
  } else {
    document.getElementById('teacher-panel').classList.remove('hidden');
    document.getElementById('admin-panel').classList.add('hidden');
    renderTeacherPanel();
  }
}

