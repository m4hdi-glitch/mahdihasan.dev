window.addEventListener('DOMContentLoaded', boot);

async function boot() {
  if (!initSupabase()) return;

  await loadSchoolSettings();
  applyBranding();

  const { data: { session } } = await db.auth.getSession();
  if (session && session.user) {
    currentUser = session.user;
    await loadProfileAndEnter();
  } else {
    showLogin();
  }

  db.auth.onAuthStateChange((event, session) => {
    if (event === 'SIGNED_OUT') {
      currentUser = null;
      currentProfile = null;
      showLogin();
    }
  });
}

async function loadSchoolSettings() {
  schoolSettings = {};
  try {
    const { data, error } = await db.from('school_settings').select('key,value');
    if (!error && data) {
      data.forEach(row => { schoolSettings[row.key] = row.value; });
    }
  } catch (e) { /* table may not exist yet; ignore */ }
}

function applyBranding() {
  const name = schoolSettings.school_name || 'School Result Portal';
  const logo = schoolSettings.logo_url || '';
  document.title = name;
  ['login-school-name', 'header-school-name'].forEach(id => {
    const el = document.getElementById(id);
    if (el) el.textContent = name;
  });
  ['login-logo', 'header-logo'].forEach(id => {
    const el = document.getElementById(id);
    if (el) el.src = logo || fallbackLogoDataUri();
  });
}

function fallbackLogoDataUri() {
  // Simple neutral placeholder logo (grey square with "S") so layout never breaks
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80">
    <rect width="80" height="80" fill="#e5e7eb"/>
    <text x="40" y="50" font-size="34" text-anchor="middle" fill="#888" font-family="Arial">S</text>
  </svg>`;
  return 'data:image/svg+xml;base64,' + btoa(svg);
}

